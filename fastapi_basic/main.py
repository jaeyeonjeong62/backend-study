# ---------------------------------------------------------------------
# STEP 1. 필요한 도구 가져오기 (import)
# ---------------------------------------------------------------------
# FastAPI : 웹 서버(앱)를 만들어 주는 핵심 도구입니다.
# Request : 사용자가 브라우저로 보낸 "요청 정보"를 담는 상자입니다.
#           (어떤 주소로 왔는지, 어떤 브라우저인지 등의 정보가 들어 있어요)
from fastapi import FastAPI, Request

# Jinja2Templates : HTML 파일을 읽어서 브라우저에 보내 주는 도구입니다.
#                   'Jinja2'는 파이썬에서 많이 쓰는 HTML 템플릿 엔진 이름이에요.
#   ※ 처음 실행 시 에러가 나면 설치가 필요합니다:  pip install jinja2
from fastapi.templating import Jinja2Templates


# ---------------------------------------------------------------------
# STEP 2. FastAPI 앱 만들기
# ---------------------------------------------------------------------
# FastAPI()를 호출하면 "웹 서버 앱" 하나가 만들어집니다.
# 이 app 변수가 앞으로 모든 페이지(주소)를 관리하는 본체가 됩니다.
# 비유: app = 가게, 아래의 각 함수 = 가게의 메뉴
app = FastAPI()


# ---------------------------------------------------------------------
# STEP 3. 템플릿(HTML) 폴더 연결하기
# ---------------------------------------------------------------------
# directory="templates" 의 의미:
#   "HTML 파일은 templates 라는 폴더 안에서 찾아라" 라고 알려 주는 것입니다.
# 주의! 서버를 실행하는 위치(폴더) 기준으로 templates 폴더를 찾습니다.
#       → 반드시 main.py가 있는 폴더에서 서버를 실행하세요.
templates = Jinja2Templates(directory="templates")


# ---------------------------------------------------------------------
# STEP 4. 첫 번째 페이지 '/' 만들기 (HTML 화면 돌려주기)
# ---------------------------------------------------------------------
# @app.get('/') 를 "데코레이터"라고 부릅니다.
#   → "누군가 '/' 주소로 GET 요청을 보내면, 바로 아래 함수를 실행해라" 라는 뜻
#   → '/' 는 사이트의 첫 화면(홈)을 의미합니다.  예) http://127.0.0.1:8000/
#   → GET 은 "정보를 보여 달라"는 가장 기본적인 요청 방식입니다.

@app.get('/')
async def read_root(request: Request):
    # async def : 비동기 함수. 여러 사용자의 요청을 동시에 효율적으로 처리합니다.
    #             (지금은 "FastAPI에서는 async def를 쓴다" 정도로 기억하면 충분!)
    # request: Request : 사용자의 요청 정보를 request 라는 이름으로 받습니다.

    # TemplateResponse(request, 템플릿 파일 이름)
    #   - request     : 사용자의 요청 정보 (템플릿을 만들 때 꼭 필요합니다)
    #   - 'home.html' : templates 폴더 안의 home.html 파일을 사용
    # 
    return templates.TemplateResponse(request, 'home.html')


# ---------------------------------------------------------------------
# STEP 5. 두 번째 페이지 '/about' 만들기 (JSON 데이터 돌려주기)
# ---------------------------------------------------------------------
# 주소: http://127.0.0.1:8000/about
# 이번에는 HTML이 아니라 "파이썬 딕셔너리"를 그대로 return 합니다.
# FastAPI는 딕셔너리를 자동으로 JSON 형식으로 바꿔서 브라우저에 보내 줍니다.
#   → 브라우저 화면: {"message": "이것은 마이 메모 앱의 소개 페이지입니다."}
# HTML 템플릿을 쓰지 않으므로 request 매개변수가 필요 없습니다.
# @app.get('/about')
# async def about():
#     return {"message": "내 소개 문장"}


# ---------------------------------------------------------------------
# STEP 6. 서버 실행하고 확인하기
# ---------------------------------------------------------------------
# 1) 터미널을 열고 main.py가 있는 폴더로 이동합니다.
# 2) 아래 명령어를 입력합니다.
#        uvicorn main:app --reload
#      - main   : main.py 파일
#      - app    : 그 파일 안의 app 변수 (STEP 2에서 만든 것)
#      - --reload : 코드를 저장하면 서버가 자동으로 다시 시작됨
# 3) 브라우저에서 아래 주소를 열어 확인합니다.
#      - http://127.0.0.1:8000/        → home.html 화면이 보이나요?
#      - http://127.0.0.1:8000/about   → JSON 메시지가 보이나요?
#      - http://127.0.0.1:8000/docs    → FastAPI가 자동으로 만든 API 문서!
# 4) 서버 종료: 터미널에서 Ctrl + C


